export function ontologyEdges(): Array<[OntologyEntry, OntologyEntry]> {
  const byName = new Map(ontology.map((entry) => [entry.name, entry]));
  return ontologyRelations.map(([left, right]) => {
    const a = byName.get(left);
    const b = byName.get(right);
    if (!a || !b) {
      throw new Error(`Missing ontology relation: ${left} — ${right}`);
    }
    return [a, b];
  });
}
